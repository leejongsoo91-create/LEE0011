// 공휴일을 넣어 둔 해
export const HOLIDAY_YEARS = [...new Set(Object.keys(HOLIDAYS).map((date) => Number(date.slice(0, 4))))].sort()

// 'YYYY-MM-DD'의 공휴일 이름 (아니면 null)
export const holidayOf = (date) => HOLIDAYS[date] ?? null

// 그 해 공휴일이 표에 들어 있는지 (없는 해는 달력 아래에 안내를 띄운다)
export const hasHolidayData = (year) => HOLIDAY_YEARS.includes(year)

// 그 달의 공휴일을 이어진 날끼리 묶는다. 예) [{ start: 24, end: 26, name: '추석' }, ...]
// "설날 연휴·설날·설날 연휴"처럼 이름이 같은 묶음(연휴)은 하나로 합친다.
export function monthHolidays(year, month) {
  const prefix = `${year}-${String(month + 1).padStart(2, '0')}-`
  const days = Object.entries(HOLIDAYS)
    .filter(([date]) => date.startsWith(prefix))
    .map(([date, name]) => ({ day: Number(date.slice(8)), name }))
    .sort((a, b) => a.day - b.day)
  const groups = []
  for (const { day, name } of days) {
    const base = name.replace(/ 연휴$/, '')
    const last = groups.at(-1)
    if (last && last.base === base && last.end === day - 1) last.end = day
    else groups.push({ start: day, end: day, base })
  }
  return groups.map(({ start, end, base }) => ({ start, end, name: end > start ? `${base} 연휴` : base }))
}
